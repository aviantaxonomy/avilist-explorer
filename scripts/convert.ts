import ExcelJS from "exceljs";
import { writeFile, mkdir, stat } from "node:fs/promises";
import { dirname } from "node:path";
import { gzipSync, constants as zlibConstants } from "node:zlib";

const SRC = "AviList-v2025-11Jun-extended.xlsx";
const SHEET = "AviList v2025 extended";
const OUT_VERBOSE = "public/data/avilist.json";
const OUT_COMPACT = "public/data/avilist-compact.json";
const OUT_COLUMNS = "src/columns.ts";

type Row = Record<string, string>;

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function runsToHtml(runs: ExcelJS.RichText[]): string {
  let out = "";
  for (const run of runs) {
    if (!run.text) continue;
    const f = run.font ?? {};
    let open = "";
    let close = "";
    if (f.bold) {
      open += "<strong>";
      close = "</strong>" + close;
    }
    if (f.italic) {
      open += "<em>";
      close = "</em>" + close;
    }
    if (f.underline) {
      open += "<u>";
      close = "</u>" + close;
    }
    if (f.strike) {
      open += "<s>";
      close = "</s>" + close;
    }
    out += open + escapeHtml(run.text) + close;
  }
  return out;
}

function cellValue(cell: ExcelJS.Cell): string | null {
  const v = cell.value;
  if (v == null || v === "") return null;
  if (typeof v === "object" && "richText" in v && Array.isArray(v.richText)) {
    return runsToHtml(v.richText);
  }
  if (typeof v === "object" && "hyperlink" in v) {
    return cell.text || v.hyperlink || null;
  }
  if (typeof v === "object" && "result" in v) {
    return v.result == null ? null : String(v.result);
  }
  if (v instanceof Date) return v.toISOString();
  return cell.text;
}

console.log(`Reading ${SRC}...`);
const wb = new ExcelJS.Workbook();
await wb.xlsx.readFile(SRC);

const sheet = wb.getWorksheet(SHEET);
if (!sheet) throw new Error(`Sheet "${SHEET}" not found`);

const headers: string[] = [];
sheet.getRow(1).eachCell({ includeEmpty: false }, (cell, col) => {
  headers[col] = cell.text;
});

const rows: Row[] = [];
let richCount = 0;
let cellCount = 0;

for (let r = 2; r <= sheet.rowCount; r++) {
  const row = sheet.getRow(r);
  const obj: Row = {};
  let hasAny = false;
  row.eachCell({ includeEmpty: false }, (cell, col) => {
    const key = headers[col];
    if (!key) return;
    const val = cellValue(cell);
    if (val == null) return;
    obj[key] = val;
    hasAny = true;
    cellCount++;
    if (/<(em|strong|u|s)>/.test(val)) richCount++;
  });
  if (hasAny) rows.push(obj);
}

console.log(
  `Parsed ${rows.length} rows, ${cellCount} non-empty cells, ${richCount} HTML-formatted cells`,
);

const columnList = headers.filter(Boolean);

const compact: (string | null)[][] = rows.map((row) =>
  columnList.map((col) => (col in row ? row[col] : null)),
);

const columnsTs = `// Generated by scripts/convert.ts — do not edit by hand.
// Index positions are the source of truth for unpacking avilist-compact.json.

export const COLUMNS = ${JSON.stringify(columnList, null, 2)} as const;

export type Column = (typeof COLUMNS)[number];
`;

const verboseJson = JSON.stringify(rows);
const compactJson = JSON.stringify(compact);

const gzipOpts = { level: zlibConstants.Z_BEST_COMPRESSION };

await mkdir(dirname(OUT_VERBOSE), { recursive: true });
await Promise.all([
  writeFile(OUT_VERBOSE, verboseJson),
  writeFile(OUT_COMPACT, compactJson),
  writeFile(OUT_COLUMNS, columnsTs),
  writeFile(OUT_VERBOSE + ".gz", gzipSync(verboseJson, gzipOpts)),
  writeFile(OUT_COMPACT + ".gz", gzipSync(compactJson, gzipOpts)),
]);

const paths = [
  OUT_VERBOSE,
  OUT_VERBOSE + ".gz",
  OUT_COMPACT,
  OUT_COMPACT + ".gz",
  OUT_COLUMNS,
];
for (const path of paths) {
  const { size } = await stat(path);
  console.log(`Wrote ${path} (${(size / 1024 / 1024).toFixed(2)} MB)`);
}
